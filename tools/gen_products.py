"""Generate site/js/products.js (public store metadata) from the private content/ folder.

Only store-page data is exported: titles, descriptions, lesson and chapter lists, one short excerpt,
page counts and prices. The product files themselves never leave content/.
Run after tools/build_pdfs.py so page counts and file sizes come from the real PDFs.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
OUT = ROOT / "site" / "js" / "products.js"
WORDS_PER_PAGE = 260  # fallback when a PDF is not built yet

# Bundle contents (owner-approved catalog plan, 02.11.2026).
BUNDLES = {49: [9, 11, 12, 18, 19], 50: [30, 31, 32, 33, 34, 35]}

# Soft cover colours per category: [background, text, shape].
CATEGORY_COLORS = {
    "טכנולוגיה": ["#2F2A6B", "#FFFFFF", "#8EC5FF"], "עיצוב": ["#FFD6E8", "#2D1B46", "#FF7EB6"],
    "שיווק": ["#FF7EB6", "#FFFFFF", "#FFD6E8"], "צילום": ["#1F2A44", "#FFE9DD", "#FFB199"],
    "פרודוקטיביות": ["#E8F1FF", "#2D1B46", "#8EC5FF"], "קריירה": ["#2D1B46", "#FFF9FB", "#C8A8FF"],
    "עסקים": ["#F3ECFF", "#2D1B46", "#8B5CF6"], "כתיבה": ["#FFF1E8", "#2D1B46", "#FFB199"],
    "יצירה": ["#FFF9FB", "#2D1B46", "#FF7EB6"], "בישול": ["#FFE2D3", "#3A1F1A", "#FF9E7A"],
    "בית": ["#E9F7EF", "#1E3A2B", "#9BD8B4"], "משפחה": ["#FFF4D6", "#3A2A10", "#FFC86B"],
    "טיולים": ["#DFF1FF", "#13314D", "#7FB8FF"], "שפות": ["#EFE7FF", "#2D1B46", "#A88BFF"],
    "תנועה": ["#E6FBF6", "#123A33", "#6FD8C1"], "חבילות": ["#8B5CF6", "#FFFFFF", "#FF7EB6"],
}
SHAPES = ["sun", "half", "ring", "bars", "dot"]
PAGE_RE = re.compile(rb"/Type\s*/Page[^s]")


def pdf_stats(n: int, words: int) -> tuple[int, float]:
    pdfs = sorted((CONTENT / "dist").glob(f"{n:02d}-*.pdf"))
    if pdfs:
        data = pdfs[0].read_bytes()
        return len(PAGE_RE.findall(data)), round(len(data) / 1_048_576, 1) or 0.1
    return max(1, round(words / WORDS_PER_PAGE)), 1.0


def paragraphs(text: str | list[str]) -> list[str]:
    if isinstance(text, list):
        return [t for t in text if t.strip()]
    return [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]


def find_course(n: int, title: str) -> dict | None:
    for folder in (CONTENT / "courses").glob("*"):
        path = folder / "course.json"
        if path.exists():
            data = json.loads(path.read_text(encoding="utf-8"))
            if int(data.get("n", 0) or 0) == n or data.get("title") == title:
                return data
    return None


def find_ebook(n: int) -> dict | None:
    for folder in (CONTENT / "ebooks").glob(f"{n:02d}-*"):
        if (folder / "meta.json").exists():
            return json.loads((folder / "meta.json").read_text(encoding="utf-8"))
    return None


def product_id(p: dict) -> str:
    return {"course": "c", "bundle": "k"}.get(p["type"], "b") + str(p["n"])


def build() -> tuple[list[dict], list[int]]:
    plan = json.loads((CONTENT / "catalog.json").read_text(encoding="utf-8"))["products"]
    out, missing = [], []
    for p in plan:
        n = p["n"]
        base = {"id": product_id(p), "n": n, "type": p["type"], "title": p["title"], "sub": p["sub"], "cat": p["cat"],
                "price": p["price"], "cv": CATEGORY_COLORS.get(p["cat"], CATEGORY_COLORS["חבילות"]), "sh": SHAPES[n % len(SHAPES)]}
        if p["type"] == "course":
            c = find_course(n, p["title"])
            if not c:
                missing.append(n)
                continue
            base.update(description=paragraphs(c.get("description", p["sub"])), outcomes=c.get("outcomes", []),
                        forWho=c.get("for", []) if isinstance(c.get("for"), list) else paragraphs(c.get("for", "")),
                        lessons=[{"title": l["title"], "summary": l.get("summary", ""), "minutes": int(l.get("minutes", 20))} for l in c["lessons"]])
        elif p["type"] == "bundle":
            base.update(includes=[f"b{i}" for i in BUNDLES[n]],
                        description=[f"{len(BUNDLES[n])} ספרים ותבניות מאותו תחום, במחיר אחד נמוך יותר מקנייה בנפרד. כל הקבצים נשלחים יחד למייל מיד אחרי התשלום."])
        else:
            m = find_ebook(n)
            if not m:
                missing.append(n)
                continue
            pages, mb = pdf_stats(n, int(m.get("words", 4000)))
            base.update(description=paragraphs(m.get("description", p["sub"])), chapters=m.get("chapters", []),
                        excerpt=m.get("excerpt", ""), pages=pages, mb=mb)
        out.append(base)
    return out, missing


def main() -> int:
    products, missing = build()
    OUT.write_text("// Generated by tools/gen_products.py from content/ — do not edit by hand.\n"
                   f"export const PRODUCTS = {json.dumps(products, ensure_ascii=False, indent=1)};\n", encoding="utf-8")
    print(f"wrote {len(products)} products to {OUT.relative_to(ROOT)}")
    if missing:
        print(f"missing content for: {missing}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

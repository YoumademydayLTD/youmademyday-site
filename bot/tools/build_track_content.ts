// Checks the topic tracks' daily messages in content/tracks/<track>/<lang>.json and writes them as one SQL file
// of idempotent upserts into bot_content (content/tracks.sql), applied with `npm run content:apply`.
// The number of days per track comes from the site (TRACKS in site/js/telegram/plans.js), the single source for
// what the site promises.
// Paid content stays out of the public repository, like the books: bot/content/ is gitignored, and so the texts
// are not a migration (migrations are committed). Re-applying overwrites days edited in /admin with the files.
// Usage: node tools/build_track_content.ts           (validate, then write content/tracks.sql)
//        node tools/build_track_content.ts --check   (validate, and fail if content/tracks.sql is not up to date)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { ALL_LANGS, messageText, parseDays, upsertSql, validateTrack, type ContentRow, type TrackSpec } from "./track-content/rules.ts";

const CONTENT_DIR = new URL("../content/tracks/", import.meta.url);
const PLANS_FILE = new URL("../../site/js/telegram/plans.js", import.meta.url);
const OUTPUT = new URL("../content/tracks.sql", import.meta.url);
// Fixed, so the generated file only changes when the texts do (same stamp as the Spark seed).
const SEED_TIME = "2026-11-04T00:00:00Z";

async function readTrackSpecs(): Promise<TrackSpec[]> {
  const plans: unknown = await import(PLANS_FILE.href);
  const tracks = (plans as { TRACKS?: unknown }).TRACKS;
  const isSpec = (t: unknown): t is TrackSpec =>
    typeof t === "object" && t !== null && typeof (t as TrackSpec).id === "string" && Number.isInteger((t as TrackSpec).days);
  if (!Array.isArray(tracks) || !tracks.every(isSpec)) throw new Error("site/js/telegram/plans.js: TRACKS must be [{id, days}]");
  return tracks.map(({ id, days }) => ({ id, days }));
}

function readJson(file: URL): unknown {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error(`${file.pathname}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

function collect(specs: readonly TrackSpec[]): { rows: ContentRow[]; problems: string[] } {
  const rows: ContentRow[] = [];
  const problems: string[] = [];
  for (const spec of specs) {
    for (const lang of ALL_LANGS) {
      const file = new URL(`${spec.id}/${lang}.json`, CONTENT_DIR);
      if (!existsSync(file)) { problems.push(`${spec.id}/${lang}: file missing`); continue; }
      const parsed = parseDays(readJson(file));
      if ("error" in parsed) { problems.push(`${spec.id}/${lang}: ${parsed.error}`); continue; }
      problems.push(...validateTrack(spec, lang, parsed.days));
      rows.push(...parsed.days.map((entry) => ({ track: spec.id, dayN: entry.day, lang, text: messageText(entry) })));
    }
  }
  return { rows, problems };
}

function upsertFileSql(rows: readonly ContentRow[]): string {
  const sorted = [...rows].sort((a, b) => a.track.localeCompare(b.track) || a.dayN - b.dayN || a.lang.localeCompare(b.lang));
  const head = [
    "-- The topic tracks' daily messages, generated by tools/build_track_content.ts from content/tracks/*/*.json.",
    "-- Do not edit by hand: change the JSON and re-run the tool. One upsert per message keeps every statement small.",
  ];
  return `${[...head, ...sorted.map((row) => upsertSql(row, SEED_TIME))].join("\n")}\n`;
}

const specs = await readTrackSpecs();
const { rows, problems } = collect(specs);
if (problems.length) {
  console.error(`${problems.length} problem(s):\n${problems.join("\n")}`);
  process.exit(1);
}
const sql = upsertFileSql(rows);
const summary = specs.map((s) => `${s.id} ${s.days}×${ALL_LANGS.length}`).join(", ");
if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  if (current !== sql) { console.error("content/tracks.sql is out of date: run node tools/build_track_content.ts"); process.exit(1); }
  console.log(`OK ${rows.length} messages (${summary}); content/tracks.sql is up to date`);
} else {
  writeFileSync(OUTPUT, sql);
  console.log(`OK ${rows.length} messages (${summary}) → content/tracks.sql`);
}
